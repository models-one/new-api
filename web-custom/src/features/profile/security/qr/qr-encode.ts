/**
 * A minimal QR Code encoder, byte mode, error-correction level M.
 *
 * WHY THIS EXISTS: the component kit ships no QR renderer and this project has no
 * QR dependency (see package.json). `POST /api/user/2fa/setup` answers with an
 * `otpauth://` URI that the user has to get into an authenticator app, and a QR
 * code is the only practical transport. Rather than add a dependency to a
 * package.json several agents are editing at once, the encoder lives here.
 *
 * SCOPE, deliberately narrow:
 *   - Byte mode only. An `otpauth://` URI is mixed-case with punctuation, so
 *     alphanumeric mode never applies and the segment optimiser is dead weight.
 *   - Error-correction level M only (15% recovery), which is what authenticator
 *     QR codes conventionally use.
 *   - Versions 1 to 40, chosen automatically as the smallest that fits.
 *
 * The algorithm is the one in ISO/IEC 18004. Correctness is pinned by
 * `__tests__/qr-encode.test.ts`, which compares whole module matrices against
 * fixtures generated by the `segno` reference encoder.
 */

/** Error-correction codewords per block, level M, indexed by version (1-40). */
const EC_CODEWORDS_PER_BLOCK_M = [
  10, 16, 26, 18, 24, 16, 18, 22, 22, 26,
  30, 22, 22, 24, 24, 28, 28, 26, 26, 26,
  26, 28, 28, 28, 28, 28, 28, 28, 28, 28,
  28, 28, 28, 28, 28, 28, 28, 28, 28, 28,
] as const

/** Number of error-correction blocks, level M, indexed by version (1-40). */
const EC_BLOCKS_M = [
  1, 1, 1, 2, 2, 4, 4, 4, 5, 5,
  5, 8, 9, 9, 10, 10, 11, 13, 14, 16,
  17, 17, 18, 20, 21, 23, 25, 26, 28, 29,
  31, 33, 35, 37, 38, 40, 43, 45, 47, 49,
] as const

/** The three mask-penalty weights and the balance weight from the specification. */
const PENALTY_RUN = 3
const PENALTY_BOX = 3
const PENALTY_FINDER_LIKE = 40
const PENALTY_BALANCE = 10

const MIN_VERSION = 1
const MAX_VERSION = 40

/** Level M's two-bit format value, used when computing the format information. */
const FORMAT_BITS_M = 0

export type QrMatrix = {
  /** Side length in modules, `4 * version + 17`. */
  size: number
  /** Row-major, `true` meaning a dark module. */
  modules: readonly (readonly boolean[])[]
  version: number
  /** The data mask (0-7) the encoder selected, or the one that was forced. */
  mask: number
}

export class QrEncodeError extends Error {
  constructor(message: string) {
    super(message)
    this.name = 'QrEncodeError'
  }
}

function bit(value: number, index: number): boolean {
  return ((value >>> index) & 1) !== 0
}

/**
 * Total module count available to data and error correction, before subtracting
 * the function patterns' codewords. Straight out of the specification's Annex.
 */
function rawDataModules(version: number): number {
  let result = (16 * version + 128) * version + 64
  if (version >= 2) {
    const alignmentCount = Math.floor(version / 7) + 2
    result -= (25 * alignmentCount - 10) * alignmentCount - 55
    if (version >= 7) result -= 36
  }
  return result
}

function totalCodewords(version: number): number {
  return Math.floor(rawDataModules(version) / 8)
}

/** Codewords left for payload once the error-correction codewords are reserved. */
export function dataCodewordCount(version: number): number {
  return (
    totalCodewords(version)
    - EC_CODEWORDS_PER_BLOCK_M[version - 1] * EC_BLOCKS_M[version - 1]
  )
}

/** Byte-mode character-count field width: 8 bits up to version 9, 16 above. */
function characterCountBits(version: number): number {
  return version <= 9 ? 8 : 16
}

/** Largest byte-mode payload, in bytes, that fits a version at level M. */
export function byteCapacity(version: number): number {
  const availableBits = dataCodewordCount(version) * 8 - 4 - characterCountBits(version)
  return Math.floor(availableBits / 8)
}

function chooseVersion(byteLength: number): number {
  for (let version = MIN_VERSION; version <= MAX_VERSION; version += 1) {
    if (byteLength <= byteCapacity(version)) return version
  }
  throw new QrEncodeError(`Content is too long to encode as a QR code (${byteLength} bytes)`)
}

// ---------------------------------------------------------------------------
// GF(256) arithmetic for Reed-Solomon, primitive polynomial 0x11D.
// ---------------------------------------------------------------------------

function gfMultiply(left: number, right: number): number {
  let product = 0
  for (let index = 7; index >= 0; index -= 1) {
    product = (product << 1) ^ ((product >>> 7) * 0x11d)
    product ^= ((right >>> index) & 1) * left
  }
  return product & 0xff
}

/** Coefficients of the generator polynomial of the given degree, highest term omitted. */
function reedSolomonDivisor(degree: number): number[] {
  const divisor = new Array<number>(degree).fill(0)
  divisor[degree - 1] = 1

  let root = 1
  for (let step = 0; step < degree; step += 1) {
    for (let index = 0; index < degree; index += 1) {
      divisor[index] = gfMultiply(divisor[index], root)
      if (index + 1 < degree) divisor[index] ^= divisor[index + 1]
    }
    root = gfMultiply(root, 0x02)
  }
  return divisor
}

function reedSolomonRemainder(data: readonly number[], divisor: readonly number[]): number[] {
  const remainder = new Array<number>(divisor.length).fill(0)
  for (const byte of data) {
    const factor = byte ^ (remainder.shift() ?? 0)
    remainder.push(0)
    for (let index = 0; index < divisor.length; index += 1) {
      remainder[index] ^= gfMultiply(divisor[index], factor)
    }
  }
  return remainder
}

// ---------------------------------------------------------------------------
// Payload assembly
// ---------------------------------------------------------------------------

function toUtf8Bytes(text: string): number[] {
  if (typeof TextEncoder !== 'undefined') return Array.from(new TextEncoder().encode(text))

  // Fallback for environments without TextEncoder; encodeURIComponent is UTF-8.
  const escaped = encodeURIComponent(text)
  const bytes: number[] = []
  for (let index = 0; index < escaped.length; index += 1) {
    if (escaped[index] === '%') {
      bytes.push(Number.parseInt(escaped.slice(index + 1, index + 3), 16))
      index += 2
    } else {
      bytes.push(escaped.charCodeAt(index))
    }
  }
  return bytes
}

/** Mode indicator, character count, payload, terminator and the 0xEC/0x11 pad. */
function buildDataCodewords(bytes: readonly number[], version: number): number[] {
  const bits: boolean[] = []
  const appendBits = (value: number, width: number) => {
    for (let index = width - 1; index >= 0; index -= 1) bits.push(bit(value, index))
  }

  appendBits(0b0100, 4)
  appendBits(bytes.length, characterCountBits(version))
  for (const byte of bytes) appendBits(byte, 8)

  const capacityBits = dataCodewordCount(version) * 8
  const terminator = Math.min(4, capacityBits - bits.length)
  for (let index = 0; index < terminator; index += 1) bits.push(false)
  while (bits.length % 8 !== 0) bits.push(false)

  const codewords: number[] = []
  for (let index = 0; index < bits.length; index += 8) {
    let byte = 0
    for (let offset = 0; offset < 8; offset += 1) byte = (byte << 1) | (bits[index + offset] ? 1 : 0)
    codewords.push(byte)
  }

  const padBytes = [0xec, 0x11]
  let padIndex = 0
  while (codewords.length < dataCodewordCount(version)) {
    codewords.push(padBytes[padIndex % 2])
    padIndex += 1
  }
  return codewords
}

/** Splits into blocks, appends each block's ECC, then interleaves both. */
function addErrorCorrectionAndInterleave(data: readonly number[], version: number): number[] {
  const blockCount = EC_BLOCKS_M[version - 1]
  const eccPerBlock = EC_CODEWORDS_PER_BLOCK_M[version - 1]
  const rawCodewords = totalCodewords(version)
  const shortBlockCount = blockCount - (rawCodewords % blockCount)
  const shortBlockLength = Math.floor(rawCodewords / blockCount)

  const divisor = reedSolomonDivisor(eccPerBlock)
  const blocks: number[][] = []
  let cursor = 0
  for (let index = 0; index < blockCount; index += 1) {
    const length = shortBlockLength - eccPerBlock + (index < shortBlockCount ? 0 : 1)
    const block = data.slice(cursor, cursor + length)
    cursor += length
    const ecc = reedSolomonRemainder(block, divisor)
    // The short blocks carry a placeholder so every block has the same array
    // length; the interleaver skips that slot rather than emitting it.
    if (index < shortBlockCount) block.push(0)
    blocks.push(block.concat(ecc))
  }

  const interleaved: number[] = []
  for (let index = 0; index < blocks[0].length; index += 1) {
    for (let blockIndex = 0; blockIndex < blocks.length; blockIndex += 1) {
      if (index === shortBlockLength - eccPerBlock && blockIndex < shortBlockCount) continue
      interleaved.push(blocks[blockIndex][index])
    }
  }
  return interleaved
}


type Canvas = {
  size: number
  modules: boolean[][]
  reserved: boolean[][]
  version: number
}

function createCanvas(version: number): Canvas {
  const size = version * 4 + 17
  return {
    size,
    version,
    modules: Array.from({ length: size }, () => new Array<boolean>(size).fill(false)),
    reserved: Array.from({ length: size }, () => new Array<boolean>(size).fill(false)),
  }
}

function setFunctionModule(canvas: Canvas, x: number, y: number, dark: boolean): void {
  canvas.modules[y][x] = dark
  canvas.reserved[y][x] = true
}

function alignmentPatternPositions(version: number): number[] {
  if (version === 1) return []

  const count = Math.floor(version / 7) + 2
  const step = version === 32 ? 26 : Math.ceil((version * 4 + 4) / (count * 2 - 2)) * 2
  const positions = [6]
  for (let position = version * 4 + 10; positions.length < count; position -= step) {
    positions.splice(1, 0, position)
  }
  return positions
}

function drawFinderPattern(canvas: Canvas, centerX: number, centerY: number): void {
  for (let dy = -4; dy <= 4; dy += 1) {
    for (let dx = -4; dx <= 4; dx += 1) {
      const x = centerX + dx
      const y = centerY + dy
      if (x < 0 || x >= canvas.size || y < 0 || y >= canvas.size) continue
      const distance = Math.max(Math.abs(dx), Math.abs(dy))
      setFunctionModule(canvas, x, y, distance !== 2 && distance !== 4)
    }
  }
}

function drawAlignmentPattern(canvas: Canvas, centerX: number, centerY: number): void {
  for (let dy = -2; dy <= 2; dy += 1) {
    for (let dx = -2; dx <= 2; dx += 1) {
      setFunctionModule(
        canvas,
        centerX + dx,
        centerY + dy,
        Math.max(Math.abs(dx), Math.abs(dy)) !== 1,
      )
    }
  }
}

function drawFormatBits(canvas: Canvas, mask: number): void {
  const value = (FORMAT_BITS_M << 3) | mask
  let remainder = value
  for (let index = 0; index < 10; index += 1) {
    remainder = (remainder << 1) ^ ((remainder >>> 9) * 0x537)
  }
  const bits = (((value << 10) | remainder) ^ 0x5412) & 0x7fff

  for (let index = 0; index <= 5; index += 1) setFunctionModule(canvas, 8, index, bit(bits, index))
  setFunctionModule(canvas, 8, 7, bit(bits, 6))
  setFunctionModule(canvas, 8, 8, bit(bits, 7))
  setFunctionModule(canvas, 7, 8, bit(bits, 8))
  for (let index = 9; index < 15; index += 1) {
    setFunctionModule(canvas, 14 - index, 8, bit(bits, index))
  }

  for (let index = 0; index < 8; index += 1) {
    setFunctionModule(canvas, canvas.size - 1 - index, 8, bit(bits, index))
  }
  for (let index = 8; index < 15; index += 1) {
    setFunctionModule(canvas, 8, canvas.size - 15 + index, bit(bits, index))
  }
  setFunctionModule(canvas, 8, canvas.size - 8, true)
}

function drawVersionBits(canvas: Canvas): void {
  if (canvas.version < 7) return

  let remainder = canvas.version
  for (let index = 0; index < 12; index += 1) {
    remainder = (remainder << 1) ^ ((remainder >>> 11) * 0x1f25)
  }
  const bits = (canvas.version << 12) | remainder

  for (let index = 0; index < 18; index += 1) {
    const dark = bit(bits, index)
    const far = canvas.size - 11 + (index % 3)
    const near = Math.floor(index / 3)
    setFunctionModule(canvas, far, near, dark)
    setFunctionModule(canvas, near, far, dark)
  }
}

function drawFunctionPatterns(canvas: Canvas): void {
  for (let index = 0; index < canvas.size; index += 1) {
    setFunctionModule(canvas, 6, index, index % 2 === 0)
    setFunctionModule(canvas, index, 6, index % 2 === 0)
  }

  drawFinderPattern(canvas, 3, 3)
  drawFinderPattern(canvas, canvas.size - 4, 3)
  drawFinderPattern(canvas, 3, canvas.size - 4)

  const positions = alignmentPatternPositions(canvas.version)
  const last = positions.length - 1
  for (let row = 0; row <= last; row += 1) {
    for (let column = 0; column <= last; column += 1) {
      const isFinderCorner = (row === 0 && column === 0)
        || (row === 0 && column === last)
        || (row === last && column === 0)
      if (isFinderCorner) continue
      drawAlignmentPattern(canvas, positions[column], positions[row])
    }
  }

  // Reserves the format and version areas; the real format bits are written
  // again once a mask has been chosen.
  drawFormatBits(canvas, 0)
  drawVersionBits(canvas)
}

function drawCodewords(canvas: Canvas, codewords: readonly number[]): void {
  let bitIndex = 0
  let right = canvas.size - 1

  while (right >= 1) {
    // Column 6 is the vertical timing pattern. The walk skips it by snapping the
    // pair one column left, and every later pair is measured from there — hence
    // the reassignment rather than a local alias.
    if (right === 6) right = 5

    for (let vertical = 0; vertical < canvas.size; vertical += 1) {
      for (let offset = 0; offset < 2; offset += 1) {
        const x = right - offset
        const upward = ((right + 1) & 2) === 0
        const y = upward ? canvas.size - 1 - vertical : vertical
        if (canvas.reserved[y][x] || bitIndex >= codewords.length * 8) continue
        canvas.modules[y][x] = bit(codewords[bitIndex >>> 3], 7 - (bitIndex & 7))
        bitIndex += 1
      }
    }

    right -= 2
  }
}

function maskApplies(mask: number, x: number, y: number): boolean {
  switch (mask) {
    case 0: return (x + y) % 2 === 0
    case 1: return y % 2 === 0
    case 2: return x % 3 === 0
    case 3: return (x + y) % 3 === 0
    case 4: return (Math.floor(x / 3) + Math.floor(y / 2)) % 2 === 0
    case 5: return ((x * y) % 2) + ((x * y) % 3) === 0
    case 6: return (((x * y) % 2) + ((x * y) % 3)) % 2 === 0
    default: return (((x + y) % 2) + ((x * y) % 3)) % 2 === 0
  }
}

function applyMask(canvas: Canvas, mask: number): void {
  for (let y = 0; y < canvas.size; y += 1) {
    for (let x = 0; x < canvas.size; x += 1) {
      if (canvas.reserved[y][x]) continue
      if (maskApplies(mask, x, y)) canvas.modules[y][x] = !canvas.modules[y][x]
    }
  }
}

/** Counts 1:1:3:1:1 finder-like sequences in a run-length history window. */
function countFinderLike(history: readonly number[]): number {
  const unit = history[1]
  const core = unit > 0
    && history[2] === unit
    && history[3] === unit * 3
    && history[4] === unit
    && history[5] === unit
  const leading = core && history[0] >= unit * 4 && history[6] >= unit ? 1 : 0
  const trailing = core && history[6] >= unit * 4 && history[0] >= unit ? 1 : 0
  return leading + trailing
}

function pushRun(history: number[], length: number, size: number): void {
  // A run that starts at the edge is preceded by the quiet zone, which counts
  // as light modules for the finder-like test.
  const adjusted = history[0] === 0 ? length + size : length
  history.pop()
  history.unshift(adjusted)
}

function scanLinePenalty(
  read: (index: number) => boolean,
  size: number,
): { runs: number; finderLike: number } {
  let runs = 0
  let finderLike = 0
  let runColor = false
  let runLength = 0
  const history = [0, 0, 0, 0, 0, 0, 0]

  for (let index = 0; index < size; index += 1) {
    if (read(index) === runColor) {
      runLength += 1
      if (runLength === 5) runs += PENALTY_RUN
      else if (runLength > 5) runs += 1
      continue
    }
    pushRun(history, runLength, size)
    if (!runColor) finderLike += countFinderLike(history) * PENALTY_FINDER_LIKE
    runColor = read(index)
    runLength = 1
  }

  if (runColor) {
    pushRun(history, runLength, size)
    runLength = 0
  }
  pushRun(history, runLength + size, size)
  finderLike += countFinderLike(history) * PENALTY_FINDER_LIKE

  return { runs, finderLike }
}

function penaltyScore(canvas: Canvas): number {
  const { size, modules } = canvas
  let score = 0

  for (let y = 0; y < size; y += 1) {
    const line = scanLinePenalty((x) => modules[y][x], size)
    score += line.runs + line.finderLike
  }
  for (let x = 0; x < size; x += 1) {
    const line = scanLinePenalty((y) => modules[y][x], size)
    score += line.runs + line.finderLike
  }

  for (let y = 0; y < size - 1; y += 1) {
    for (let x = 0; x < size - 1; x += 1) {
      const color = modules[y][x]
      if (
        color === modules[y][x + 1]
        && color === modules[y + 1][x]
        && color === modules[y + 1][x + 1]
      ) {
        score += PENALTY_BOX
      }
    }
  }

  let dark = 0
  for (const row of modules) {
    for (const module of row) if (module) dark += 1
  }
  const total = size * size
  score += (Math.ceil(Math.abs(dark * 20 - total * 10) / total) - 1) * PENALTY_BALANCE

  return score
}

/**
 * Encodes `text` as a QR Code matrix at error-correction level M.
 *
 * @param forcedMask - Pins the data mask instead of selecting the lowest-penalty
 *   one. Only the tests use it, to compare against reference fixtures per mask.
 * @throws {QrEncodeError} when the content exceeds version 40's byte capacity.
 */
export function encodeQr(text: string, forcedMask?: number): QrMatrix {
  const bytes = toUtf8Bytes(text)
  const version = chooseVersion(bytes.length)
  const codewords = addErrorCorrectionAndInterleave(buildDataCodewords(bytes, version), version)

  let best: { canvas: Canvas; mask: number } | null = null
  const candidates = forcedMask === undefined ? [0, 1, 2, 3, 4, 5, 6, 7] : [forcedMask]
  let bestScore = Number.POSITIVE_INFINITY

  for (const mask of candidates) {
    const canvas = createCanvas(version)
    drawFunctionPatterns(canvas)
    drawCodewords(canvas, codewords)
    applyMask(canvas, mask)
    drawFormatBits(canvas, mask)

    const score = penaltyScore(canvas)
    if (score < bestScore) {
      bestScore = score
      best = { canvas, mask }
    }
  }

  if (!best) throw new QrEncodeError('No QR code mask could be selected')

  return {
    size: best.canvas.size,
    modules: best.canvas.modules,
    version,
    mask: best.mask,
  }
}

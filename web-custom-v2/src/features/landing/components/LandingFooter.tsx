import { useQuery } from '@tanstack/react-query'
import { Link } from '@tanstack/react-router'
import { useTranslation } from 'react-i18next'

import modelsOneMark from '@/assets/models-one-mark.png'
import { BrandMark } from '@/components/system/BrandMark'
import { sanitizeDocumentHtml } from '@/features/content/sanitize'
import { serverStatusQuery } from '@/lib/api/status'

export function LandingFooter() {
  const { t } = useTranslation()
  const status = useQuery(serverStatusQuery()).data
  const systemName = status?.system_name?.trim() ?? ''
  const logo = status?.logo?.trim() || modelsOneMark
  const docsLink = status?.docs_link?.trim() ?? ''
  // System settings → Site → Footer. Operators put their ICP and public-security filing
  // numbers here, so it is shown as written (sanitised) instead of a fixed template.
  const filingHtml = sanitizeDocumentHtml(status?.footer_html?.trim() ?? '')
  const year = new Date().getFullYear()

  return (
    <footer className="border-t border-[var(--home-line)] bg-[var(--home-paper)] px-4 sm:px-8">
      <div className="mx-auto grid max-w-[1200px] gap-10 py-14 md:grid-cols-[1.4fr_repeat(3,1fr)]">
        <div>
          <BrandMark
            logo={logo}
            markClassName="h-8 max-w-40"
            name={systemName}
            nameClassName="text-lg font-bold text-[var(--home-ink)]"
          />
          <p className="mt-4 max-w-xs text-sm leading-6">{t('One OpenAI-compatible API for every major model.')}</p>
        </div>

        <nav aria-label={t('Product')}>
          <h2 className="text-sm font-bold text-[var(--home-ink)]">{t('Product')}</h2>
          <ul className="mt-4 space-y-3 text-sm">
            <li><Link className="home-footer-link" to="/models">{t('Models')}</Link></li>
            <li><Link className="home-footer-link" to="/pricing">{t('Pricing')}</Link></li>
            <li><Link className="home-footer-link" to="/rankings">{t('Rankings')}</Link></li>
          </ul>
        </nav>

        <nav aria-label={t('Resources')}>
          <h2 className="text-sm font-bold text-[var(--home-ink)]">{t('Resources')}</h2>
          <ul className="mt-4 space-y-3 text-sm">
            {docsLink === '' ? null : (
              <li>
                <a className="home-footer-link" href={docsLink} rel="noreferrer" target="_blank">{t('Docs')}</a>
              </li>
            )}
            <li><Link className="home-footer-link" to="/about">{t('About')}</Link></li>
            <li><a className="home-footer-link" href="https://github.com/QuantumNous/new-api">GitHub</a></li>
          </ul>
        </nav>

        <nav aria-label={t('Legal')}>
          <h2 className="text-sm font-bold text-[var(--home-ink)]">{t('Legal')}</h2>
          <ul className="mt-4 space-y-3 text-sm">
            <li><Link className="home-footer-link" to="/privacy-policy">{t('Privacy Policy')}</Link></li>
            <li><Link className="home-footer-link" to="/user-agreement">{t('Terms of Service')}</Link></li>
          </ul>
        </nav>
      </div>

      <div className="-mx-4 border-t border-[var(--home-line)] px-4 sm:-mx-8 sm:px-8">
        <div className="mx-auto flex max-w-[1200px] flex-col gap-2 py-6 text-xs leading-6 text-[var(--home-faint)]">
          {filingHtml === '' ? null : (
            <div className="home-filing" dangerouslySetInnerHTML={{ __html: filingHtml }} />
          )}
          <p>{t('Content generated by AI on this site is for reference only.')}</p>
          <p>
            © {year} {systemName}
          </p>
        </div>
      </div>
    </footer>
  )
}
